namespace WinApi.User32.Enums
{
    /// <summary>
    /// Показаны имена символьных констант, шестнадцатеричные значения и эквиваленты мыши или
    /// клавиатуры для кодов виртуальных ключей, используемых системой.
    /// </summary>
    public enum VirtualKey
    {
        /// <summary>
        /// Левая кнопка мыши.
        /// </summary>
        VK_LBUTTON = 0x01,

        /// <summary>
        /// Правая кнопка мыши.
        /// </summary>
        VK_RBUTTON = 0x02,

        /// <summary>
        /// Обработка контроля и прерывания.
        /// </summary>
        VK_CANCEL = 0x03,

        /// <summary>
        /// Средняя кнопка мыши.
        /// </summary>
        VK_MBUTTON = 0x04,

        /// <summary>
        /// Кнопка мыши X1.
        /// </summary>
        VK_XBUTTON1 = 0x05,

        /// <summary>
        /// Кнопка мыши X2.
        /// </summary>
        VK_XBUTTON2 = 0x06,

        /// <summary>
        /// Зарезервировано.
        /// </summary>
        VK_Empty_1 = 0x07,

        /// <summary>
        /// Backspace.
        /// </summary>
        VK_BACK = 0x08,

        /// <summary>
        /// Tab.
        /// </summary>
        VK_TAB = 0x09,

        /// <summary>
        /// Зарезервировано.
        /// </summary>
        VK_Empty_2 = 0x0A,

        /// <summary>
        /// Зарезервировано.
        /// </summary>
        VK_Empty_3 = 0x0B,

        /// <summary>
        /// Клавиша CLEAR.
        /// </summary>
        VK_CLEAR = 0x0C,

        /// <summary>
        /// Клавиша ВВОД.
        /// </summary>
        VK_RETURN = 0x0D,

        /// <summary>
        /// Не присвоено.
        /// </summary>
        VK_Empty_4 = 0x0E,

        /// <summary>
        /// Не присвоено.
        /// </summary>
        VK_Empty_5 = 0x0F,

        /// <summary>
        /// Клавиша SHIFT.
        /// </summary>
        VK_SHIFT = 0x10,

        /// <summary>
        /// Клавиша CTRL.
        /// </summary>
        VK_CONTROL = 0x11,


    }
}